const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const ts = require('typescript')
const context = { exports: {} }
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/leaderboard-ranking.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context)
const { rankLeaderboard, rankLabel } = context.exports
const ranks = points => Array.from(rankLeaderboard(points.map((totalPoints, id) => ({ totalPoints, id }))), student => student.rank)
assert.deepEqual(ranks([90, 90, 90, 89]), [1, 1, 1, 4])
assert.deepEqual(ranks([90, 85, 85, 80, 80, 0, 0]), [1, 2, 2, 4, 4, 6, 6])
assert.deepEqual(ranks([90, 90, 90, 90, 89]), [1, 1, 1, 1, 5])
assert.deepEqual(ranks([89.999, 90, 90.001, 89.99]), [1, 1, 1, 4], 'equal displayed precision means equal rank')
assert.deepEqual(ranks([0, 0]), [1, 1])
assert.deepEqual(ranks([]), [])
const input = [{ totalPoints: 80 }, { totalPoints: 100 }]
assert.deepEqual(Array.from(rankLeaderboard(input), student => student.totalPoints), [100, 80])
assert.equal(input[0].totalPoints, 80, 'ranking must not mutate cached reports')
assert.equal(rankLeaderboard([{ totalPoints: 90 }, { totalPoints: 90 }])[0].tied, true)
assert.equal(rankLabel(1, true), 'Joint 1st')
assert.equal(rankLabel(11), '11th')
assert.equal(rankLabel(12), '12th')
assert.equal(rankLabel(13), '13th')
assert.equal(rankLabel(22), '22nd')
console.log('Shared competition ranks, ties at display precision, zero scores, non-mutation and ordinal labels passed.')
