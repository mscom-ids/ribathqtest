const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
process.env.TS_NODE_PROJECT = path.resolve('backend/tsconfig.json');
require('../backend/node_modules/ts-node/register/transpile-only');
const ExcelJS = require('../backend/node_modules/exceljs');
const {createValuationWorkbook} = require('../backend/src/services/valuation-workbook.service');
const allocation = require('../backend/src/exam-allocation-nov26.json');
(async()=>{
    const centers = allocation.centers.map(c=>({id:c.code,code:c.code,name:`Exam Center ${c.code}`,examiner_name:`Examiner ${c.code}`}));
    const students = allocation.centers.flatMap(c=>c.students.map(s=>({center_id:c.code,serial_no:s.serial_no,student_id:s.admission_no,student_name:s.name,standard:s.standard})));
    const subjects = [...new Set(students.map(s=>s.standard))].map(standard=>({id:standard,name:'Hifz Valuation',standard,question_count:10,question_max:10}));
    const first = students[0];
    const data = {exam:{title:'HALF YEARLY HIFZ EXAMINATION NOV 26'},centers,students,subjects,valuations:[{student_id:first.student_id,subject_id:first.standard,marks:[9.5,9.4,0.25,...Array(7).fill(10)],juz:''}]};
    const output = await createValuationWorkbook(data);
    const workbook = new ExcelJS.Workbook(); await workbook.xlsx.load(output);
    assert.equal(workbook.worksheets.length,10);
    const sheet = workbook.getWorksheet('Center A');
    assert.equal(sheet.getCell('A1').value,data.exam.title);
    assert.equal(sheet.getCell('P1').master.address,'A1');
    assert.equal(sheet.getCell('B4').value,first.student_id);
    assert.equal(sheet.getCell('F4').value,9.5);
    assert.equal(sheet.getCell('P4').value.result,89.15);
    assert.equal(sheet.getCell('P5').value.result ?? '','');
    assert.equal(sheet.getCell('P4').value.formula,'IF(COUNT(F4:O4)=0,"",SUM(F4:O4))');
    assert.equal(sheet.getCell('F4').dataValidation.type,'decimal');
    assert.equal(sheet.getCell('F4').border.bottom.style,'thin');
    assert.equal(sheet.pageSetup.orientation,'landscape');
    assert.equal(sheet.pageSetup.printTitlesRow,'1:3');
    for(const center of centers) {
        const s = workbook.getWorksheet(`Center ${center.code}`);
        const assigned = students.filter(s=>s.center_id===center.id);
        assert.equal(s.getCell('A4').value,1);
        assert.equal(s.rowCount,assigned.length+4);
        assigned.forEach((student,index)=>assert.equal(s.getCell(index+4,2).value,student.student_id));
        assert.match(s.getCell(assigned.length+4,1).value,/Invigilator: Examiner/);
    }
    const blank = new ExcelJS.Workbook(); await blank.xlsx.load(await createValuationWorkbook({...data,centers:[centers[0]]},true));
    assert.equal(blank.worksheets.length,1);assert.equal(blank.worksheets[0].getCell('F4').value,null);assert.equal(blank.worksheets[0].getCell('P4').value.result ?? '','');
    const moved = {...data,students:students.map(s=>s===first?{...s,center_id:'B',serial_no:14}:s)};
    const transferred = new ExcelJS.Workbook();await transferred.xlsx.load(await createValuationWorkbook(moved));
    assert(!transferred.getWorksheet('Center A').getColumn(2).values.includes(first.student_id));
    assert(transferred.getWorksheet('Center B').getColumn(2).values.includes(first.student_id));
    const varied = new ExcelJS.Workbook();await varied.xlsx.load(await createValuationWorkbook({...data,centers:[centers[0]],subjects:[...subjects,{id:'extra',name:'Tajweed',standard:first.standard,question_count:5,question_max:5}]}));
    assert.equal(varied.worksheets.length,2);
    assert.equal(varied.worksheets[1].columnCount,11);
    fs.mkdirSync('tmp/exam-workbook',{recursive:true});fs.writeFileSync('tmp/exam-workbook/valuation-preview.xlsx',output);
    console.log('PASS center allocations, decimals, blanks, formulas, styles, print setup, transfers, single-center and multiple-subject sheets');
})().catch(e=>{console.error(e);process.exitCode=1});
